import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';
import { pathToFileURL } from 'node:url';
import { interceptDesign, origin } from './helpers/offline-design.mjs';

test('录单分离银行卡来源、订单类型和共享卡分类，GPT 未登记卡仍可确认付款', { timeout: 45_000 }, async t => {
  const playwright = process.env.ID_RECHARGE_QA_PLAYWRIGHT;
  const { chromium } = await import(playwright ? pathToFileURL(playwright).href : 'playwright');
  const browser = await chromium.launch({ channel: process.env.ID_RECHARGE_QA_BROWSER_CHANNEL });
  t.after(() => browser.close());
  const fixture = JSON.parse(await readFile(new URL('../docs/audits/2026-11-06-design-review/visual-fixtures.json', import.meta.url)));
  const actor = { id: 'qa-order-admin', name: '合成管理员', role: 'admin' };
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const mock = await interceptDesign(context, { localFixtures: fixture, actor });
  const poolId = 'recharge:24';
  const cardTypeA = { id: 'card-type-wise-pan', name: 'wise潘', active: true };
  const cardTypeB = { id: 'card-type-wise-jia', name: 'wise佳', active: true };
  let types = { version: 1, items: [cardTypeA, cardTypeB], assignments: { [poolId]: cardTypeA.id } };
  const typeWrites = [], orderWrites = [];
  await context.route('**/api/local/card-types', async route => {
    if (route.request().method() !== 'GET') {
      const command = route.request().postDataJSON();
      typeWrites.push(command);
      assert.equal(command.version, types.version);
      types = { ...types, version: types.version + 1 };
      if (command.action === 'assign') types.assignments[command.cardId] = command.typeId;
      if (command.action === 'add') types.items.push({ id: 'qa-new-type', name: command.name, active: true });
      if (command.action === 'rename') types.items.find(row => row.id === command.id).name = command.name;
      if (command.action === 'remove') types.items.find(row => row.id === command.id).active = false;
    }
    await route.fulfill({ json: types });
  });
  await context.route('**/api/local/order-cards', route => route.fulfill({ json: { items: [
    { id: poolId, last4: '4242', active: true, usageCount: 2, status: '正常' }
  ] } }));
  await context.route('**/api/local/auth/order-owners', route => route.fulfill({ json: { items: [actor] } }));
  await context.route('**/api/local/auth/display-names', route => route.fulfill({ json: { items: [actor] } }));
  await context.route('**/api/local/commerce', route => {
    if (route.request().method() === 'GET') return route.fallback();
    const command = route.request().postDataJSON();
    orderWrites.push(command);
    fixture.commerce = { version: command.version + 1, data: command.data };
    return route.fulfill({ json: fixture.commerce });
  });
  const page = await context.newPage();
  page.setDefaultTimeout(6500);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const field = name => page.locator(`#main #commerce-${name}`);
  const drawer = page.locator('#drawer[open]');
  const accept = () => page.locator('#confirm-dialog [data-action="confirm-accept"]').click();
  await page.goto(`${origin}/#/workspace/order/claude`);
  await field('cardTypeId').waitFor();
  const mode = field('proMaterialMode');
  assert.deepEqual(await mode.locator('option').evaluateAll(options => options.map(item => item.value)),
    ['none', 'manual_card', 'pool_card', 'tenant_card']);
  await mode.selectOption('pool_card');
  const serial = field('proCardSerial');
  await serial.fill('00017-POOL');
  const pool = field('proPoolCardId');
  await pool.locator(`option[value="${poolId}"]`).waitFor({ state: 'attached' });
  await pool.evaluate((select, id) => { select.value = id; select.dispatchEvent(new Event('change', { bubbles: true })); }, poolId);
  assert.equal(await field('cardTypeId').inputValue(), cardTypeA.id);
  await field('cardTypeId').selectOption(cardTypeB.id);
  assert.equal(typeWrites.length, 0, '订单类型下拉不改共享卡分类');
  await mode.selectOption('tenant_card');
  assert.equal(await serial.isVisible(), false, '租户真实卡不显示卡序列号');
  assert.equal(await field('tenantId-picker').isVisible(), true);
  assert.equal(await field('cardId-picker').isVisible(), true);
  assert.equal(await field('proPoolCardId-picker').isVisible(), false);
  await mode.selectOption('none');
  assert.equal(await serial.isVisible(), true, '银行卡未登记时可填写已知卡序列号');
  assert.equal(await field('tenantId-picker').isVisible(), false);
  assert.equal(await field('proCardNumber').isVisible(), false);
  await mode.selectOption('pool_card');
  assert.equal(await serial.inputValue(), '00017-POOL');
  assert.equal(await pool.inputValue(), poolId);
  assert.equal(await field('cardTypeId').inputValue(), cardTypeB.id);
  await page.locator('#main [data-action="commerce-card-type-assign"]:visible').click();
  await drawer.locator('#commerce-assignment-type').selectOption(cardTypeB.id);
  await drawer.locator('button[form="commerce-card-type-assignment-form"]').click();
  await drawer.waitFor({ state: 'hidden' });
  assert.deepEqual(typeWrites[0], { action: 'assign', version: 1, cardId: poolId, typeId: cardTypeB.id });
  await field('plan').selectOption('Max 5x');
  assert.equal(await mode.isVisible(), true);
  assert.equal(await field('cardTypeId').isVisible(), true);
  await field('payment').selectOption('苹果内购');
  assert.equal(await serial.isVisible(), false);
  assert.equal(await field('cardTypeId').isVisible(), false);

  await page.goto(`${origin}/#/workspace/order/gpt`);
  await field('cardTypeId').waitFor();
  await field('email').fill('draft-kept@example.test');
  assert.equal(await page.locator('#commerce-order-form [data-action="commerce-card-types"]').count(), 0, '录单中不再保留类型管理入口');
  await page.evaluate(() => window.IDDesignAPI.go('settings/payment-countries'));
  await page.waitForURL(`${origin}/#/settings/payment-countries`);
  await page.getByRole('tab', { name: '银行卡类型', exact: true }).click();
  assert.equal(await page.getByRole('tab', { name: '银行卡类型', exact: true }).getAttribute('aria-selected'), 'true');
  await page.getByRole('button', { name: '新增类型', exact: true }).click();
  await drawer.locator('#commerce-card-type-name').fill('测试订阅卡');
  await drawer.locator('button[form="commerce-card-type-form"]').click();
  await drawer.waitFor({ state: 'hidden' });
  await page.locator('[data-action="commerce-card-type-edit"][data-id="qa-new-type"]').click();
  await drawer.locator('#commerce-card-type-id[value="qa-new-type"]').waitFor({ state: 'attached' });
  await drawer.locator('#commerce-card-type-name').fill('改名订阅卡');
  await drawer.locator('button[form="commerce-card-type-form"]').click();
  await drawer.waitFor({ state: 'hidden' });
  await page.getByText('改名订阅卡', { exact: true }).waitFor();
  await page.locator('[data-action="commerce-card-type-remove"][data-id="qa-new-type"]').click();
  await accept();
  await page.locator('[data-row-id="qa-new-type"]').getByText('已停用', { exact: true }).waitFor();
  await page.evaluate(() => window.IDDesignAPI.go('workspace/order/gpt'));
  await field('email').waitFor();
  assert.equal(await field('email').inputValue(), 'draft-kept@example.test', '通过系统设置管理类型后仍保留录单草稿');
  assert.deepEqual(typeWrites.map(({ action }) => action), ['assign', 'add', 'rename', 'remove']);
  const customer = fixture.commerce.data.customers.find(row => row.active !== false);
  assert.ok(customer);
  await field('customerId').evaluate((select, id) => {
    select.value = id;
    select.dispatchEvent(new Event('change', { bubbles: true }));
  }, customer.id);
  await field('email').fill('no-card-fixture@example.test');
  await mode.selectOption('');
  await field('paidAmount').fill('20');
  await field('saleAmount').fill('100');
  await field('start').fill('2026-11-12T12:00');
  await field('expiry').fill('2026-12-12T12:00');
  await field('cardTypeId').selectOption(cardTypeA.id);
  const submit = page.locator('#main button[form="commerce-order-form"][type="submit"]');
  assert.equal(await page.locator('#main [data-commerce-field="confirmations"]').count(), 0);
  assert.equal(orderWrites.length, 0);
  await submit.click();
  await page.locator('#toast').filter({ hasText: '订单提交成功' }).waitFor();
  assert.equal(orderWrites.length, 1, '确认提交只保存一次');
  assert.equal(await page.locator('#confirm-dialog[open]').count(), 0);
  assert.equal(new URL(page.url()).hash, '#/workspace/order/gpt');
  const saved = orderWrites.at(-1)?.data.orders.find(row => row.email === 'no-card-fixture@example.test');
  assert.ok(saved);
  assert.equal(saved.cardId, '');
  assert.equal(saved.cardTypeId, cardTypeA.id);
  assert.equal(saved.paidConfirmed, true);
  assert.equal(saved.receiptConfirmed, true);
  assert.equal(saved.costConfirmed, true);
  assert.equal(saved.includeIssueFee, false);
  assert.equal(saved.issueFeeSnapshot.pending, true);
  assert.deepEqual(errors, []);
  assert.deepEqual(mock.external, []);
});
